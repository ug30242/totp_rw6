const fs=require('node:fs');
const crypto=require('node:crypto');
const engine=fs.readFileSync('src/common/totp.js','utf8').replace(/export\s*\{[^}]*\};\s*$/, '');
const display=fs.readFileSync('src/common/display-name.js','utf8').replace('export function','function');
const script=engine+'\n'+display+'\n'+fs.readFileSync('web/app.js','utf8');
const style=fs.readFileSync('web/style.css','utf8');
const license=fs.readFileSync('node_modules/jsqr/LICENSE','utf8');
if(license.includes('*/')) throw new Error('Unexpected license comment terminator');
const decoder='/* jsQR 1.4.0, Apache-2.0; original distribution, no functional modifications.\n'+license+'\n*/\n'+fs.readFileSync('node_modules/jsqr/dist/jsQR.js','utf8');
const hash=s=>crypto.createHash('sha256').update(s).digest('base64');
const csp=`default-src 'none'; connect-src 'none'; img-src blob: data:; script-src 'sha256-${hash(script)}' 'sha256-${hash(decoder)}'; style-src 'sha256-${hash(style)}'; base-uri 'none'; form-action 'none'`;
let html=fs.readFileSync('web/template.html','utf8');
for(const [key,value] of Object.entries({CSP:csp,SCRIPT:script,STYLE:style,QRDECODER:decoder})) html=html.replace('@@'+key+'@@',()=>value);
fs.writeFileSync('web/index.html',html);
fs.writeFileSync('web/THIRD_PARTY_NOTICES.txt','jsQR 1.4.0 (https://github.com/cozmo/jsQR), Apache-2.0\nBundled unmodified from its npm distribution for local image decoding.\n\n'+license);
console.log('Built standalone offline web/index.html; network connections blocked by CSP');
