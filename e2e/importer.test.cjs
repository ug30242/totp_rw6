const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const http=require('node:http');
const {chromium}=require('playwright-core');
const QRCode=require('qrcode');
const uri='otpauth://totp/Example:alice?secret=JBSWY3DPEHPK3PXP&algorithm=SHA256&digits=8&period=60';
const executablePath=process.env.CHROMIUM_PATH||['/usr/bin/chromium','/usr/bin/google-chrome'].find(fs.existsSync);
test('offline helper decodes a local QR image and URI with zero network requests',async()=>{
  assert(executablePath,'Install Chromium or set CHROMIUM_PATH');
  const server=http.createServer((req,res)=>{res.setHeader('Content-Type','text/html; charset=utf-8');res.end(fs.readFileSync('web/index.html'));});
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  const browser=await chromium.launch({executablePath,args:['--no-sandbox']});
  try {
    const context=await browser.newContext();const page=await context.newPage();const errors=[];const requests=[];
    page.on('pageerror',e=>errors.push(e.message));
    await page.goto('http://127.0.0.1:'+server.address().port);
    await context.setOffline(true);
    page.on('request',request=>{if(/^https?:/.test(request.url()))requests.push(request.url());});
    await page.locator('#accounts').fill(uri);await page.locator('#prepare').click();
    await page.waitForFunction(()=>document.getElementById('results').textContent.includes('Example (alice)'));
    assert.equal(await page.locator('.secret').textContent(),'JBSW Y3DP EHPK 3PXP');
    assert((await page.locator('#results').textContent()).includes('SHA256'));
    await page.locator('#clear').click();assert.equal(await page.locator('#accounts').inputValue(),'');assert.equal(await page.locator('#results').textContent(),'');
    const png=await QRCode.toBuffer(uri,{type:'png',margin:4,width:480});
    await page.locator('#qr-image').setInputFiles({name:'otp.png',mimeType:'image/png',buffer:png});
    await page.waitForFunction(()=>document.getElementById('results').textContent.includes('Example (alice)'));
    assert.equal(await page.locator('#accounts').inputValue(),uri);
    await page.locator('#accounts').fill('otpauth://hotp/a?secret=MY');await page.locator('#prepare').click();
    await page.waitForFunction(()=>document.getElementById('status').textContent.includes('TOTP'));
    assert.equal(await page.locator('#results').textContent(),'');
    await page.locator('#clear').click();assert.equal(await page.locator('#qr-image').inputValue(),'');
    const originalUrl=page.url();
    const link=await QRCode.toBuffer('https://ug30242.github.io/totp_rw6/',{type:'png',margin:4,width:480});
    await page.locator('#qr-image').setInputFiles({name:'link.png',mimeType:'image/png',buffer:link});
    await page.waitForFunction(()=>document.getElementById('status').textContent.includes('otpauth://'));
    assert.equal(page.url(),originalUrl);assert.equal(await page.locator('#results').textContent(),'');
    assert.deepEqual(errors,[]);assert.deepEqual(requests,[]);
    const csp=await page.locator('meta[http-equiv="Content-Security-Policy"]').getAttribute('content');assert(csp.includes("connect-src 'none'"));
  } finally {await browser.close();await new Promise(resolve=>server.close(resolve));}
});
